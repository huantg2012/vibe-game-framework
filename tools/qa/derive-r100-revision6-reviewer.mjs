function derive(source) {
  let result = source;
  for (const [before, after] of replacements) {
    assert.equal(result.split(before).length, 2, 'Every bounded source replacement must match exactly once');
    result = result.replace(before, after);
  }
  let restored = result;
  for (const [before, after] of [...replacements].reverse()) restored = restored.replace(after, before);
  assert.equal(restored, source, 'All unrelated accounting and diagnosis bytes remain exact');
  return result;
}
