/** Compact low-grade authorship is independent of the reviewed mother catalog. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { parseNativeSpatialConstructionReference } from '../../src/generation/world-study/native-spatial-construction-reference.ts';
import { parseNativeConstructionShore } from '../../src/generation/world-study/native-spatial-construction-shore.ts';

const sha = value => createHash('sha256').update(value).digest('hex');
const source = file => {
  assert(/^data\/rift-native-construction-low-[a-z-]+\.csv$/.test(file));
  const csv = fs.readFileSync(file, 'utf8');
  return { csv, sourceHash: sha(csv) };
};
const file = 'data/rift-native-construction-low.csv';
const [header, ...lines] = fs.readFileSync(file, 'utf8').trim().split(/\r?\n/);
assert.equal(header, 'world_id,enabled,reference_csv,shore_csv,frame_width_px,frame_height_px,target_walk_area_px2,planning_cell_factor,assembly_scale_multiplier');
const rows = lines.map(line => {
  const [worldId, enabled, referencePath, shorePath, width, height, area, factor, multiplier] = line.split(',');
  assert(['cinder-ridge', 'crystal-fibre', 'ruptured-film'].includes(worldId));
  assert(['true', 'false'].includes(enabled));
  const reference = source(referencePath), shore = source(shorePath);
  const parsed = parseNativeSpatialConstructionReference(reference.csv, reference.sourceHash);
  const boundary = parseNativeConstructionShore(shore.csv, shore.sourceHash);
  assert.equal(parsed.worldId, worldId);
  // sourceGrade selects the complete physical mother, independently of the
  // departure grade and the low-specific placement authored in this file.
  assert.equal(parsed.grade, 'medium');
  assert.equal(parsed.seed, 20261012);
  assert.equal(boundary.referenceId, parsed.id);
  const intent = { frameWidthPx: Number(width), frameHeightPx: Number(height),
    targetWalkAreaPx2: Number(area), planningCellFactor: Number(factor) };
  assert([intent.frameWidthPx, intent.frameHeightPx].every(n => Number.isInteger(n) && n >= 1024 && n % 32 === 0));
  assert(intent.frameWidthPx <= 3072 && intent.frameHeightPx <= 2304);
  assert(Number.isFinite(intent.targetWalkAreaPx2) && intent.targetWalkAreaPx2 >= 100000
    && intent.targetWalkAreaPx2 <= intent.frameWidthPx * intent.frameHeightPx);
  assert(Number.isFinite(intent.planningCellFactor) && intent.planningCellFactor > 0 && intent.planningCellFactor <= 2);
  const assemblyScaleMultiplier = Number(multiplier);
  assert(Number.isFinite(assemblyScaleMultiplier) && assemblyScaleMultiplier >= .5 && assemblyScaleMultiplier <= 1);
  const row = { worldId, enabled: enabled === 'true', reference, shore, intent, assemblyScaleMultiplier };
  return { ...row, sourceHash: sha(JSON.stringify(row)) };
});
assert(rows.length >= 1 && rows.length <= 3);
assert.equal(new Set(rows.map(row => row.worldId)).size, rows.length);
const target = 'src/generated/r100-native-low-construction.ts';
const text = `/** Generated by tools/native-spatial/codegen-low-construction.mjs; edit the author CSV. */\nexport const NATIVE_LOW_CONSTRUCTION_SOURCES = ${JSON.stringify(rows, null, 2)} as const;\n`;
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), text, 'Low construction catalog differs from CSV');
else fs.writeFileSync(target, text);
console.log(JSON.stringify({ status: 'passed', worlds: rows.map(row => row.worldId), file: target }));
