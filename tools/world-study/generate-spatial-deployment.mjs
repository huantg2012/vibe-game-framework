import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const source = readFileSync(new URL('../../data/rift-spatial-deployment.csv', import.meta.url), 'utf8');
const [header, row, ...extra] = source.trim().split(/\r?\n/);
const keys = header.split(','), values = row?.split(',');
if (!values || values.length !== keys.length || extra.length) throw new Error('Expected one spatial deployment policy row');
const policy = Object.fromEntries(keys.map((key, index) => [key, Number(values[index])]));
if (Object.values(policy).some(value => !Number.isFinite(value) || value <= 0)) throw new Error('Invalid spatial deployment policy value');
const output = `// GENERATED by tools/world-study/generate-spatial-deployment.mjs from data/rift-spatial-deployment.csv.\nexport const R100_SPATIAL_DEPLOYMENT = ${JSON.stringify({ ...policy, sourceHash: createHash('sha256').update(source).digest('hex') }, null, 2)} as const;\n`;
const target = new URL('../../src/generated/rift-spatial-deployment-data.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Spatial deployment data is stale');
} else writeFileSync(target, output);
console.log(`Spatial deployment CSV ${process.argv.includes('--check') ? 'verified' : 'generated'}`);
