import assert from 'node:assert/strict';
import {InventoryStore} from '../../../../../src/systems/inventory-store';
import {createWeaponInstance} from '../../../../../src/systems/equipment-lifecycle';
import {PreparationNarrationAdapter} from '../../../../../src/narrative/preparation-narration-adapter';
import {PREPARATION_NARRATION_POOLS} from '../../../../../src/generated/preparation-narration-data';
const store=new InventoryStore(), state=store.getState();
const original=createWeaponInstance('crowbar_plain',true,'original'); original.usesRemaining=10;
const alternate=createWeaponInstance('crowbar_plain',true,'alternate');
state.items=[{id:'original',kind:'weapon',weapon:original,location:{kind:'carried'}},{id:'alternate',kind:'weapon',weapon:alternate,location:{kind:'stash'}}];
state.equipment.weaponId='original'; assert(store.loadState(state));
const adapter=new PreparationNarrationAdapter(store),journey=adapter.createJourney();
const selected={grade:'low' as const,visible:true,paused:false};
const first=journey.update(250,selected); assert(PREPARATION_NARRATION_POOLS['prepare.worn_weapon'].lines.some(row=>row.text===first));
journey.update(0,{...selected,visible:false});
assert(store.prepareWeapon('alternate').ok); journey.update(16,{...selected,visible:false});
assert(store.prepareWeapon('original').ok); journey.update(16,{...selected,visible:false});
const returned=journey.update(250,selected);
journey.update(0,{...selected,visible:false});
assert(store.prepareWeapon('alternate').ok); journey.update(16,{...selected,visible:false});
assert(store.prepareWeapon('original').ok); journey.update(16,{...selected,visible:false});
const third=journey.update(250,selected);
console.log(JSON.stringify({originalStateRestored:JSON.stringify(store.getState())===JSON.stringify(state),noDamageIncreaseOrGrowthOccurred:true,first,returned,secondWornUtterance:PREPARATION_NARRATION_POOLS['prepare.worn_weapon'].lines.some(row=>row.text===returned),third,scope:'Actual InventoryStore preparation methods + adapter + journey, driving frame flags to match equipment page. Not a browser run.'},null,2));
journey.destroy();adapter.destroy();
