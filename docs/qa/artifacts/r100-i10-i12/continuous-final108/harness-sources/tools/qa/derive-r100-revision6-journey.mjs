/** Keep the approved policy15 input source immutable. Its revision5-only result
 * assertion is adapted for revision6; no gameplay input or policy changes. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import ts from 'typescript';

const originalPath = 'tools/qa/r100-i09-journey.mjs';
const originalHash = 'dfde2f7429261bb81008e1f341c7e862ee6d0f71bc8c629f553b948066022bb3';
const target = 'tools/qa/r100-revision6-journey.mjs';
const manifestPath = 'docs/qa/artifacts/r100-i10-i12/controller-revision6/derivation.json';
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const before = "assert.equal(receipt.identity.generation.package.algorithmRevision,5,'I07-I09 real journeys require frozen revision5')";
const after = "assert.equal(receipt.identity.generation.package.algorithmRevision,6,'I10-I12 real journeys require frozen revision6')";
function derive(source) {
  const ast = ts.createSourceFile(originalPath, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  assert.equal(ast.parseDiagnostics.length, 0);
  const matches = [];
  function visit(node) {
    if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)
      && node.expression.expression.getText(ast) === 'assert' && node.expression.name.text === 'equal'
      && node.arguments[0]?.getText(ast) === 'receipt.identity.generation.package.algorithmRevision') matches.push(node);
    ts.forEachChild(node, visit);
  }
  visit(ast); assert.equal(matches.length, 1, 'Exactly one version result assertion');
  const node = matches[0]; assert.equal(node.getText(ast), before, 'Refuse any unexpected input-policy edit');
  const body = source.slice(0, node.getStart(ast)) + after + source.slice(node.end);
  assert.equal(body.replace(after, before), source, 'All other source bytes remain exact');
  return { body, start: node.getStart(ast), end: node.end };
}
const source = fs.readFileSync(originalPath, 'utf8'); assert.equal(sha(source), originalHash);
const change = derive(source);
if (process.argv.includes('--self-check')) {
  assert.throws(() => derive(source.replace(before, before.replace(',5,', ',4,'))));
  assert.throws(() => derive(source + `\n${before};\n`));
  assert.throws(() => derive(source.replace(before, '')));
  assert.equal(change.body.slice(0, change.start), source.slice(0, change.start));
  assert.equal(change.body.slice(change.start + after.length), source.slice(change.end));
  console.log('PASS revision6 adapter: only exact version assertion changes; altered, duplicate and missing guards rejected');
  process.exit(0);
}
const output = `// GENERATED by tools/qa/derive-r100-revision6-journey.mjs. Input policy15 is unchanged.\n// Only the result algorithmRevision assertion is 6; original policy source remains immutable.\n${change.body}`;
const manifest = { schemaVersion: 1, inputPolicyRevision: 15, algorithmRevision: 6,
  original: { path: originalPath, sha256: originalHash }, executor: { path: target, sha256: sha(output) },
  transformation: { kind: 'result-version-assertion-only', before, after, originalStart: change.start, originalEnd: change.end,
    allOtherSourceBytesExact: true },
  tool: { path: 'tools/qa/derive-r100-revision6-journey.mjs', sha256: sha(fs.readFileSync(new URL(import.meta.url))) },
  limitation: 'Metadata admission only. No input, navigation, observation, threat, duration, tool, pickup or outcome rule changes.' };
const json = JSON.stringify(manifest, null, 2) + '\n';
if (process.argv.includes('--write')) {
  assert(!fs.existsSync(target) && !fs.existsSync(manifestPath), 'Adapters and receipts are append-only');
  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(target, output); fs.writeFileSync(manifestPath, json);
} else {
  assert.equal(fs.readFileSync(target, 'utf8'), output); assert.equal(fs.readFileSync(manifestPath, 'utf8'), json);
}
console.log(JSON.stringify({ status: 'pass', inputPolicyRevision: 15, algorithmRevision: 6, target, sha256: manifest.executor.sha256 }));
