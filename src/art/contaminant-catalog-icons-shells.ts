/** Fixed local anchor [0,0]. The item is painted OVER these remnants, never obscured. */
export function paintRemnant(appearanceId:string,size:24|32):PixelCanvas {
  const p=new PixelCanvas(size),b=size===32,x=b?16:12,y=b?25:18;
  p.anchor=[x,y];
  switch(appearanceId){
    case 'wax_parcel':p.poly([[x-3,y],[x+2,y-1],[x+4,y+2],[x,y+3],[x-4,y+1]],M.wax[1]);p.line([[x-2,y],[x+1,y+1],[x+2,y+2]],M.wax[3]);break;
    case 'resin_nodule':p.poly([[x-3,y],[x+1,y-1],[x+4,y+1],[x+2,y+3],[x-3,y+2]],M.amber[1]);p.line([[x-2,y],[x+1,y]],M.amber[3]);break;
    case 'ash_cocoon':p.poly([[x-4,y],[x+2,y-1],[x+3,y+2],[x-2,y+3]],M.cloth[1]);p.line([[x-3,y+1],[x+1,y],[x+2,y+2]],M.cloth[3]);break;
    case 'layered_hide':p.poly([[x-4,y],[x+1,y-1],[x+4,y+1],[x+1,y+3],[x-3,y+2]],M.leather[1]);p.line([[x-2,y],[x+2,y+1],[x,y+2]],M.leather[3]);break;
    case 'ceramic_seal':p.poly([[x-3,y-1],[x+2,y],[x+4,y+2],[x-3,y+2]],M.ceramic[1]);p.line([[x-3,y],[x,y+1],[x+3,y+1]],M.ceramic[3]);break;
    case 'salt_case':p.poly([[x-4,y],[x+2,y-1],[x+4,y+1],[x+2,y+3],[x-4,y+2]],M.bone[1]);p.line([[x-3,y+1],[x+2,y],[x+3,y+1]],M.bone[3]);break;
    case 'stitched_pouch':p.poly([[x-4,y],[x+2,y],[x+4,y+2],[x-3,y+3]],M.plum[1]);p.line([[x-3,y+1],[x+2,y+1]],M.plum[2]);p.dot(x-1,y+1,M.paper[2]);p.dot(x+1,y+2,M.paper[2]);break;
    case 'thin_shell_ovoid':p.poly([[x-4,y],[x-1,y+2],[x+2,y+1],[x+4,y],[x+2,y+3],[x-2,y+3]],M.bone[2]);p.line([[x-3,y+1],[x-1,y+2],[x+2,y+2]],M.bone[3]);break;
    default:throw new Error(`Unknown catalog appearance: ${appearanceId}`);
  }
  return p;
}
